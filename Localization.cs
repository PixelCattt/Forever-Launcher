    public static string GetIn(string lang, string key, params object[] args)
    {
      Dictionary<string, string> translations;
      switch (lang)
      {
        case "de": translations = Localization.German; break;
        case "es": translations = Localization.Spanish; break;
        case "ru": translations = Localization.Russian; break;
        default: translations = Localization.English; break;
      }
      
      if (!translations.TryGetValue(key, out string format) && !Localization.English.TryGetValue(key, out format))
        return key;

      return args != null && args.Length != 0 ? string.Format(format, args) : format;
    }

    public static void Load()
    {
      string language = Settings.LoadLanguage();
      Localization.Lang = Array.IndexOf<string>(Localization.Langs, language) >= 0 ? language : "en";
    }

    public static void Save() => Settings.SaveLanguage(Localization.Lang);
  }
